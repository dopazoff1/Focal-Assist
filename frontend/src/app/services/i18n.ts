@Injectable({ providedIn: 'root' })
export class I18nService {
  readonly supportedLanguages = UI_LANGUAGE_OPTIONS;
  private readonly languageSubject = new BehaviorSubject<UiLanguage>(getStoredUiLanguage());
  readonly language$ = this.languageSubject.asObservable();

  constructor() {
    this.applyLanguage(this.languageSubject.value);
  }

  get language(): UiLanguage {
    return this.languageSubject.value;
  }

  get locale(): string {
    return languageToLocale(this.language);
  }

  setLanguage(language: UiLanguage): void {
    if (language === this.language) return;
    this.applyLanguage(language);
    this.languageSubject.next(language);
  }

  t(key: string, params?: Record<string, string | number>): string {
    const table = TRANSLATIONS[this.language] || TRANSLATIONS.en;
    const fallback = TRANSLATIONS.en[key];
    let result = table[key] ?? fallback ?? key;
    if (!params) return result;

    for (const [paramKey, value] of Object.entries(params)) {
      result = result.replaceAll(`{${paramKey}}`, String(value ?? ''));
    }
    return result;
  }

  private applyLanguage(language: UiLanguage): void {
    storeUiLanguage(language);
    if (typeof document !== 'undefined') {
      document.documentElement.lang = language;
      document.documentElement.dir = isRtlLanguage(language) ? 'rtl' : 'ltr';
    }
  }
}

